import AppKit
import ApplicationServices
import Carbon.HIToolbox

/// Reads the selected text in the frontmost app and replaces it. Both need Accessibility access:
/// reading asks the focused element first and falls back to a simulated ⌘C; replacing pastes,
/// which works in every app. The user's clipboard is restored afterwards.
enum TextBridge {
    static var isTrusted: Bool { AXIsProcessTrusted() }

    /// Shows the system prompt that leads to System Settings → Accessibility.
    static func requestTrust() {
        let options = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
        AXIsProcessTrustedWithOptions(options)
    }

    static func openAccessibilitySettings() {
        if let url = URL(string: "x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility") {
            NSWorkspace.shared.open(url)
        }
    }

    /// Each step is noted in caret.log (when debugCaret is on), so a miss shows where it failed.
    static func selectedText() async -> String? {
        if let app = NSWorkspace.shared.frontmostApplication { exposeAccessibility(of: app) }
        if let text = accessibilitySelectedText(), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { return text }
        // Some apps (Typora, editors built on web views) only hand the selection over by copying, and
        // copying a whole document can take a moment; a missed ⌘C gets one more try.
        for attempt in 1...2 {
            if let text = await copySelection(wait: 1.0), !text.isEmpty {
                CaretLog.note("read: copied (try \(attempt))")
                return text
            }
        }
        CaretLog.note("read: nothing found")
        return nil
    }

    /// Puts [text] where [original] was selected, then gives the user their clipboard back. If the
    /// selection moved while the result was coming, [original] is found and selected again first.
    static func replaceSelection(_ original: String, with text: String) async {
        let outcome = ensureSelected(original)
        CaretLog.note("replace: selection \(outcome)")
        let pasteboard = NSPasteboard.general
        let saved = PasteboardSnapshot(pasteboard)
        pasteboard.clearContents()
        // Marked as temporary, so clipboard managers (Paste, Raycast, Maccy) don't keep it.
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        pasteboard.writeObjects([item])
        postShortcut(keyCode: kVK_ANSI_V)
        // The target app reads the clipboard asynchronously; give it time before restoring.
        try? await Task.sleep(nanoseconds: 600_000_000)
        saved.restore(to: pasteboard)
    }

    /// "kept", "reselected", or why neither (the paste then goes wherever the caret is).
    private static func ensureSelected(_ original: String) -> String {
        guard let element = focusedElement() else { return "unknown (no focused element)" }
        func flat(_ s: String) -> String { s.replacingOccurrences(of: "\r\n", with: "\n").replacingOccurrences(of: "\r", with: "\n") }
        if let selected = element.string(kAXSelectedTextAttribute), flat(selected) == flat(original) { return "kept" }
        guard let value = element.string(kAXValueAttribute) else { return "unknown (no value)" }
        // Accessibility counts UTF-16 units, like NSString.
        let found = (value as NSString).range(of: original)
        guard found.location != NSNotFound else { return "lost, original not found" }
        let ok = element.setRange(kAXSelectedTextRangeAttribute, CFRange(location: found.location, length: found.length))
        return ok ? "reselected" : "unknown (can't select)"
    }

    private static func focusedElement() -> AXUIElement? {
        let system = AXUIElementCreateSystemWide()
        AXUIElementSetMessagingTimeout(system, 0.3)
        return system.element(kAXFocusedUIElementAttribute)
    }

    /// Waits (up to [limit]) until ⌘, ⇧, ⌥ and ⌃ are up, so a simulated ⌘C isn't read as ⇧⌘C.
    static func waitForModifiersReleased(limit: TimeInterval = 0.6) async {
        let held: CGEventFlags = [.maskCommand, .maskShift, .maskAlternate, .maskControl]
        let deadline = Date().addingTimeInterval(limit)
        while !CGEventSource.flagsState(.combinedSessionState).intersection(held).isEmpty, Date() < deadline {
            try? await Task.sleep(nanoseconds: 20_000_000)
        }
    }

    /// Chromium and Electron apps build their accessibility tree only when asked to.
    private static var exposedPIDs = Set<pid_t>()

    static func exposeAccessibility(of app: NSRunningApplication) {
        guard exposedPIDs.insert(app.processIdentifier).inserted else { return }
        AXUIElementSetAttributeValue(AXUIElementCreateApplication(app.processIdentifier), "AXManualAccessibility" as CFString, kCFBooleanTrue)
    }

    /// The selected text, or failing that the selected range cut out of the field's value (some apps
    /// report an empty selected text but a correct range).
    private static func accessibilitySelectedText() -> String? {
        guard let element = focusedElement() else {
            CaretLog.note("read: no focused element")
            return nil
        }
        if let text = element.string(kAXSelectedTextAttribute), !text.isEmpty {
            CaretLog.note("read: accessibility selected text")
            return text
        }
        if let range = element.range(kAXSelectedTextRangeAttribute), range.length > 0,
           let value = element.string(kAXValueAttribute) as NSString?,
           range.location >= 0, range.location + range.length <= value.length {
            CaretLog.note("read: accessibility range")
            return value.substring(with: NSRange(location: range.location, length: range.length))
        }
        CaretLog.note("read: accessibility has no selection (\(element.string(kAXRoleAttribute) ?? "?"))")
        return nil
    }

    /// Browsers and Electron apps often don't expose the selection; copying it always works.
    private static func copySelection(wait: TimeInterval) async -> String? {
        let pasteboard = NSPasteboard.general
        let saved = PasteboardSnapshot(pasteboard)
        let before = pasteboard.changeCount
        postShortcut(keyCode: kVK_ANSI_C)
        let deadline = Date().addingTimeInterval(wait)
        while pasteboard.changeCount == before, Date() < deadline {
            try? await Task.sleep(nanoseconds: 25_000_000)
        }
        guard pasteboard.changeCount != before else {
            CaretLog.note("read: ⌘C changed nothing in \(wait)s")
            return nil
        }
        // Plain text, or the text of rich content when an app copies only that.
        var text = pasteboard.string(forType: .string)
        if text == nil, let data = pasteboard.data(forType: .rtf) {
            text = NSAttributedString(rtf: data, documentAttributes: nil)?.string
        }
        if text == nil, let data = pasteboard.data(forType: .html) {
            text = NSAttributedString(html: data, documentAttributes: nil)?.string
        }
        if text == nil { CaretLog.note("read: copied, but no text in \(pasteboard.types?.map(\.rawValue) ?? [])") }
        saved.restore(to: pasteboard)
        return text
    }

    private static func postShortcut(keyCode: Int) {
        let source = CGEventSource(stateID: .combinedSessionState)
        for keyDown in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(keyCode), keyDown: keyDown)
            event?.flags = .maskCommand
            event?.post(tap: .cghidEventTap)
        }
    }
}

/// Every item and type on the clipboard, so a borrowed clipboard can be put back as it was.
private struct PasteboardSnapshot {
    private let items: [[NSPasteboard.PasteboardType: Data]]

    init(_ pasteboard: NSPasteboard) {
        items = (pasteboard.pasteboardItems ?? []).map { item in
            var types: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { types[type] = data }
            }
            return types
        }
    }

    func restore(to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        let restored = items.map { types -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in types { item.setData(data, forType: type) }
            return item
        }
        if !restored.isEmpty { pasteboard.writeObjects(restored) }
    }
}
